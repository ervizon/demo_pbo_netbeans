    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // Tombol Hapus (berdasarkan NIM di jTextField2)
        String nim = jTextField2.getText().trim();
        int jawab = JOptionPane.showConfirmDialog(
            this, "Hapus data " + nim + "?", "Konfirmasi", JOptionPane.YES_NO_OPTION
        );
        if (jawab == JOptionPane.YES_OPTION) {
            String hasil = controller.hapus(nim);
            if (!hasil.equals("OK")) {
                JOptionPane.showMessageDialog(this, hasil);
                return;
            }
            tampilkanData();
            bersihkanForm();
        }
    }//GEN-LAST:event_jButton3ActionPerformed

