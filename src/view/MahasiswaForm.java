    private void jTable2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable2MouseClicked
        // Klik baris tabel -> isi form & kunci NIM
        int baris = jTable2.getSelectedRow();
        if (baris >= 0) {
            jTextField2.setText(modelTabel.getValueAt(baris, 0).toString()); // NIM
            jTextField1.setText(modelTabel.getValueAt(baris, 1).toString()); // Nama
            jTextField3.setText(modelTabel.getValueAt(baris, 2).toString()); // Program Studi
            jTextField2.setEditable(false);
        }
    }//GEN-LAST:event_jTable2MouseClicked

